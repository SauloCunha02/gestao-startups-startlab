/* Monta uma pagina de pitch autocontida (HTML + CSS + JS num arquivo so),
   com os dados da startup dentro dela e cronometro de 2, 3 ou 5 minutos.
   O arquivo gerado nao depende da internet nem do StartLab: abre e apresenta. */
(function (raiz) {
  'use strict';

  // Proporcao de tempo de cada parte, igual a do roteiro da Trilha Extrema
  // (25 + 35 + 25 + 25 + 10 = 120 s). Em 3 e 5 minutos, cresce na mesma medida.
  var PARTES = [
    {titulo: 'O problema e o cliente', peso: 25},
    {titulo: 'A startup', peso: 35},
    {titulo: 'Como ganha dinheiro', peso: 25},
    {titulo: 'O que o teste mostrou', peso: 25},
    {titulo: 'O que ainda não sabemos', peso: 10}
  ];

  function escapar(texto) {
    return String(texto == null ? '' : texto)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;')
      .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  }

  // Evita que um "</script>" digitado pelo aluno quebre o arquivo gerado.
  function embutir(valor) {
    return JSON.stringify(valor).replace(/</g, '\\u003c').replace(/\u2028|\u2029/g, '');
  }

  var ESTILO = [
    ':root{color-scheme:light;--bg:#f6f7f2;--card:#fff;--tinta:#203d33;--suave:#65756b;--linha:#dfe5db;--marca:#b4541b;--marca-suave:#f6e0cd;--verde:#194c3b}',
    '*{box-sizing:border-box}',
    'body{margin:0;background:var(--bg);color:var(--tinta);font:16px/1.6 "Segoe UI",Arial,sans-serif;min-height:100vh;display:flex;flex-direction:column}',
    'button{font:inherit;cursor:pointer;color:inherit;border:0;background:none}',
    'h1,h2,h3{margin:0;line-height:1.15;letter-spacing:-.03em}',
    'p{margin:0}',
    ':focus-visible{outline:3px solid var(--verde);outline-offset:3px}',
    '[hidden]{display:none!important}',
    '.barra{height:6px;background:var(--linha);flex:none}',
    '.barra span{display:block;height:100%;width:0;background:var(--marca);transition:width .5s linear}',
    '.topo{display:flex;align-items:center;gap:16px;flex-wrap:wrap;justify-content:space-between;padding:14px 26px;border-bottom:1px solid var(--linha);background:var(--card)}',
    '.relogio{font-size:30px;font-weight:720;font-variant-numeric:tabular-nums;letter-spacing:-.03em;color:var(--marca)}',
    '.relogio.estourou{color:#b00020}',
    '.parcial{font-size:12.5px;color:var(--suave)}',
    '.controles{display:flex;gap:8px;flex-wrap:wrap;align-items:center}',
    '.btn{border:1px solid var(--linha);background:var(--card);border-radius:999px;padding:9px 16px;font-weight:650}',
    '.btn:hover{background:var(--bg)}',
    '.btn.forte{background:var(--marca);color:#fff;border-color:transparent}',
    '.minutos{display:flex;gap:4px;border:1px solid var(--linha);border-radius:999px;padding:3px;background:var(--card)}',
    '.minutos button{border-radius:999px;padding:6px 13px;font-size:13.5px;font-weight:650;color:var(--suave)}',
    '.minutos button[aria-pressed=true]{background:var(--marca);color:#fff}',
    'main{flex:1;display:grid;place-items:center;padding:34px 26px}',
    '.slide{max-width:900px;width:100%;background:var(--card);border:1px solid var(--linha);border-radius:22px;padding:44px;box-shadow:0 14px 40px #1c3b2d10;animation:entrar .32s ease}',
    '@keyframes entrar{from{opacity:0;transform:translateY(14px)}to{opacity:1;transform:none}}',
    '.etiqueta{font-size:11px;font-weight:750;letter-spacing:.14em;text-transform:uppercase;color:var(--suave)}',
    '.slide h2{font-size:clamp(26px,4.4vw,40px);margin:12px 0 22px;color:var(--marca)}',
    '.slide h1{font-size:clamp(34px,7vw,64px);color:var(--marca);margin:14px 0 18px;overflow-wrap:anywhere}',
    '.slide .proposta{font-size:clamp(17px,2.4vw,23px);line-height:1.5;max-width:40ch}',
    '.campo{margin-bottom:20px}',
    '.campo:last-child{margin-bottom:0}',
    '.campo b{display:block;font-size:11px;font-weight:750;letter-spacing:.1em;text-transform:uppercase;color:var(--suave);margin-bottom:6px}',
    '.campo p{font-size:clamp(15px,2vw,19px);line-height:1.6;white-space:pre-wrap;overflow-wrap:anywhere}',
    '.vazio{color:var(--suave);font-style:italic}',
    '.conta{display:flex;gap:12px;flex-wrap:wrap;margin-top:6px}',
    '.conta div{background:var(--marca-suave);border-radius:12px;padding:12px 16px;min-width:0}',
    '.conta small{display:block;font-size:10.5px;font-weight:750;letter-spacing:.08em;color:var(--suave)}',
    '.conta b{font-size:19px;letter-spacing:-.02em}',
    '.rodape{display:flex;align-items:center;justify-content:space-between;gap:16px;flex-wrap:wrap;padding:14px 26px;border-top:1px solid var(--linha);background:var(--card);font-size:13px;color:var(--suave)}',
    '.passos{display:flex;gap:6px}',
    '.ponto{width:26px;height:5px;border-radius:999px;background:var(--linha)}',
    '.ponto.feito{background:var(--marca)}',
    '.dica{font-size:12.5px}',
    '.aviso{margin-top:18px;border-left:4px solid var(--marca);background:var(--marca-suave);border-radius:10px;padding:13px 16px;font-size:13px;line-height:1.6;color:var(--suave)}',
    '@media (max-width:620px){.slide{padding:26px 20px;border-radius:16px}.topo,.rodape{padding:12px 16px}main{padding:20px 14px}.relogio{font-size:24px}}',
    '@media (prefers-reduced-motion:reduce){.slide{animation:none}*{transition:none!important}}',
    '@media print{.topo,.rodape,.barra{display:none}.slide{box-shadow:none;border:0;break-after:page;max-width:none}main{display:block;padding:0}}'
  ].join('\n');

  var ROTEIRO = [
    'var DADOS=__DADOS__;',
    'var PARTES=__PARTES__;',
    'var total=120,indice=-1,restante=0,gasto=0,prazo=0,relogio=null,correndo=false;',
    '',
    'function pad(n){return String(n).padStart(2,"0")}',
    'function mmss(s){var v=Math.abs(s);return (s<0?"-":"")+pad(Math.floor(v/60))+":"+pad(v%60)}',
    '',
    '// Distribui o tempo escolhido entre as partes, na proporcao do roteiro.',
    '// Usa maior resto: o segundo que sobra vai para quem ficou mais perto de',
    '// ganha-lo, em vez de todo o erro cair sempre na ultima parte.',
    'function orcamentos(){',
    '  var soma=PARTES.reduce(function(a,p){return a+p.peso},0);',
    '  var exatos=PARTES.map(function(p){return total*p.peso/soma});',
    '  var base=exatos.map(Math.floor);',
    '  var sobra=total-base.reduce(function(a,b){return a+b},0);',
    '  var ordem=exatos.map(function(v,i){return {i:i,resto:v-Math.floor(v)}})',
    '    .sort(function(a,b){return b.resto-a.resto});',
    '  for(var k=0;k<sobra;k++)base[ordem[k%ordem.length].i]++;',
    '  return base;',
    '}',
    '',
    'function campo(rotulo,valor){',
    '  var vazio=!valor||!String(valor).trim();',
    '  return "<div class=\\"campo\\"><b>"+rotulo+"</b><p"+(vazio?" class=\\"vazio\\"":"")+">"+(vazio?"(não preenchido na trilha)":valor)+"</p></div>";',
    '}',
    '',
    'function corpoSlide(i){',
    '  var d=DADOS;',
    '  if(i===0)return campo("Para quem é",d.publico)+campo("O que trava hoje",d.trava);',
    '  if(i===1)return campo("O que entrega",d.entrega)+campo("Proposta",d.proposta);',
    '  if(i===2){',
    '    var c=d.conta?"<div class=\\"conta\\"><div><small>RECEITA</small><b>"+d.conta.receita+"</b></div><div><small>GASTOS</small><b>"+d.conta.gastos+"</b></div><div><small>SALDO DO MÊS</small><b>"+d.conta.saldo+"</b></div></div>":"";',
    '    return campo("Quem usa e quem paga",d.papeis)+campo("Como o cliente chega",d.canal)+c;',
    '  }',
    '  if(i===3)return campo("O que fizemos",d.prova)+campo("O que as pessoas fizeram",d.resultado);',
    '  return campo("O que ainda não sabemos",d.duvida)+"<p class=\\"aviso\\">Esta startup foi montada em um sprint de 50 minutos, com duas conversas e dois testes. É um ponto de partida investigado, não um negócio comprovado.</p>";',
    '}',
    '',
    'function capa(){',
    '  document.getElementById("slide").innerHTML=',
    '    "<p class=\\"etiqueta\\">Pitch · StartLab</p><h1>"+(DADOS.nome||"Sua startup")+"</h1>"+',
    '    "<p class=\\"proposta\\">"+(DADOS.proposta||"Preencha a proposta na Trilha Extrema para ela aparecer aqui.")+"</p>"+',
    '    "<p class=\\"aviso\\">Escolha a duração e clique em Iniciar. Avance com a seta direita, a barra de espaço ou clicando em Avançar. O relógio mostra quanto resta no total e quanto sobra nesta parte.</p>";',
    '  document.getElementById("titulo-parte").textContent="Capa";',
    '  document.getElementById("parcial").textContent=total/60+" minutos no total";',
    '  document.getElementById("relogio").textContent=mmss(total);',
    '  pontos();',
    '}',
    '',
    'function mostrar(i){',
    '  indice=i;',
    '  var orc=orcamentos();',
    '  document.getElementById("slide").innerHTML=',
    '    "<p class=\\"etiqueta\\">Parte "+(i+1)+" de "+PARTES.length+" · "+orc[i]+" segundos</p>"+',
    '    "<h2>"+PARTES[i].titulo+"</h2>"+corpoSlide(i);',
    '  document.getElementById("titulo-parte").textContent=PARTES[i].titulo;',
    '  gasto=0;',
    '  pontos();',
    '  parcial();',
    '}',
    '',
    'function pontos(){',
    '  document.getElementById("passos").innerHTML=PARTES.map(function(_,i){',
    '    return "<span class=\\"ponto"+(i<=indice?" feito":"")+"\\"></span>";',
    '  }).join("");',
    '}',
    '',
    'function parcial(){',
    '  if(indice<0)return;',
    '  var orc=orcamentos()[indice],sobra=orc-gasto;',
    '  document.getElementById("parcial").textContent=sobra>=0',
    '    ? "Nesta parte: "+mmss(sobra)+" de "+mmss(orc)',
    '    : "Nesta parte: "+mmss(sobra)+" além do previsto";',
    '}',
    '',
    'function tique(){',
    '  var agora=Math.max(0,Math.ceil((prazo-Date.now())/1000));',
    '  gasto+=restante-agora;',
    '  restante=agora;',
    '  var r=document.getElementById("relogio");',
    '  r.textContent=mmss(restante);',
    '  r.classList.toggle("estourou",restante===0);',
    '  document.getElementById("barra").style.width=((total-restante)/total*100)+"%";',
    '  parcial();',
    '  if(restante===0)parar();',
    '}',
    '',
    'function iniciar(){',
    '  if(indice<0)mostrar(0);',
    '  correndo=true;restante=restante||total;prazo=Date.now()+restante*1000;',
    '  relogio=setInterval(tique,250);',
    '  document.getElementById("iniciar").textContent="Pausar";',
    '}',
    'function parar(){clearInterval(relogio);relogio=null;correndo=false;document.getElementById("iniciar").textContent=restante?"Continuar":"Iniciar";}',
    '',
    'function avancar(passo){',
    '  var proximo=indice+passo;',
    '  if(proximo<0||proximo>=PARTES.length)return;',
    '  mostrar(proximo);',
    '}',
    '',
    'function definirMinutos(min){',
    '  total=min*60;restante=total;gasto=0;',
    '  document.querySelectorAll(".minutos button").forEach(function(b){',
    '    b.setAttribute("aria-pressed",String(Number(b.dataset.min)===min));',
    '  });',
    '  document.getElementById("barra").style.width="0%";',
    '  if(indice<0)capa(); else {document.getElementById("relogio").textContent=mmss(total);mostrar(indice);}',
    '}',
    '',
    'document.getElementById("iniciar").addEventListener("click",function(){correndo?parar():iniciar()});',
    'document.getElementById("avancar").addEventListener("click",function(){avancar(1)});',
    'document.getElementById("voltar").addEventListener("click",function(){avancar(-1)});',
    'document.getElementById("zerar").addEventListener("click",function(){',
    '  parar();indice=-1;restante=total;gasto=0;',
    '  document.getElementById("barra").style.width="0%";',
    '  document.getElementById("iniciar").textContent="Iniciar";',
    '  capa();',
    '});',
    'document.querySelectorAll(".minutos button").forEach(function(b){',
    '  b.addEventListener("click",function(){definirMinutos(Number(b.dataset.min))});',
    '});',
    'document.addEventListener("keydown",function(e){',
    '  if(e.key==="ArrowRight"||e.key===" "){e.preventDefault();avancar(1)}',
    '  else if(e.key==="ArrowLeft"){e.preventDefault();avancar(-1)}',
    '});',
    '',
    'definirMinutos(2);'
  ].join('\n');

  function montar(dados, minutos) {
    var corpo = [
      '<div class="barra"><span id="barra"></span></div>',
      '<header class="topo">',
      '  <div>',
      '    <output class="relogio" id="relogio" aria-label="Tempo restante">02:00</output>',
      '    <p class="parcial" id="parcial"></p>',
      '  </div>',
      '  <div class="controles">',
      '    <div class="minutos" role="group" aria-label="Duração do pitch">',
      '      <button type="button" data-min="2" aria-pressed="true">2 min</button>',
      '      <button type="button" data-min="3" aria-pressed="false">3 min</button>',
      '      <button type="button" data-min="5" aria-pressed="false">5 min</button>',
      '    </div>',
      '    <button class="btn forte" id="iniciar" type="button">Iniciar</button>',
      '    <button class="btn" id="voltar" type="button">← Voltar</button>',
      '    <button class="btn" id="avancar" type="button">Avançar →</button>',
      '    <button class="btn" id="zerar" type="button">Zerar</button>',
      '  </div>',
      '</header>',
      '<main><section class="slide" id="slide" aria-live="polite"></section></main>',
      '<footer class="rodape">',
      '  <span id="titulo-parte">Capa</span>',
      '  <div class="passos" id="passos" aria-hidden="true"></div>',
      '  <span class="dica">Setas ou barra de espaço para navegar</span>',
      '</footer>'
    ].join('\n');

    var script = ROTEIRO
      .replace('__DADOS__', embutir(dados))
      .replace('__PARTES__', embutir(PARTES));

    return [
      '<!doctype html>',
      '<html lang="pt-BR">',
      '<head>',
      '<meta charset="utf-8">',
      '<meta name="viewport" content="width=device-width, initial-scale=1">',
      '<title>Pitch — ' + escapar(dados.nome || 'Sua startup') + '</title>',
      '<style>',
      ESTILO,
      '</style>',
      '</head>',
      '<body>',
      corpo,
      '<script>',
      script,
      '<\/script>',
      '</body>',
      '</html>',
      ''
    ].join('\n');
  }

  raiz.GerarPitch = {partes: PARTES, montar: montar};
})(window);
